use std::cell::Cell;
use std::fmt::Display;

use cineo_core::app::UiLanguage;
use fastframe_i18n::{LanguageTag, Translator};

#[allow(
    clippy::match_same_arms,
    reason = "generated by fastframe-i18n from the catalogs"
)]
mod catalogs {
    include!(concat!(env!("OUT_DIR"), "/catalogs.rs"));

    pub(super) use self::{
        de::Translator as De, es::Translator as Es, es_419::Translator as Es419,
    };
    pub(super) use self::{fr::Translator as Fr, it::Translator as It, pt_br::Translator as PtBr};
    pub(super) use self::{ru::Translator as Ru, zh_cn::Translator as ZhCn};
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum Locale {
    #[default]
    English,
    Spanish,
    LatinAmericanSpanish,
    Russian,
    Italian,
    German,
    French,
    BrazilianPortuguese,
    SimplifiedChinese,
}

impl fastframe_i18n::Locale for Locale {
    fn catalog(self) -> Option<&'static dyn Translator> {
        match self {
            Self::English => None,
            Self::Spanish => Some(&catalogs::Es),
            Self::LatinAmericanSpanish => Some(&catalogs::Es419),
            Self::Russian => Some(&catalogs::Ru),
            Self::Italian => Some(&catalogs::It),
            Self::German => Some(&catalogs::De),
            Self::French => Some(&catalogs::Fr),
            Self::BrazilianPortuguese => Some(&catalogs::PtBr),
            Self::SimplifiedChinese => Some(&catalogs::ZhCn),
        }
    }
}

impl Locale {
    pub const ALL: [Self; 9] = [
        Self::English,
        Self::Spanish,
        Self::LatinAmericanSpanish,
        Self::Russian,
        Self::Italian,
        Self::German,
        Self::French,
        Self::BrazilianPortuguese,
        Self::SimplifiedChinese,
    ];

    pub(crate) fn from_tag(tag: &LanguageTag) -> Option<Self> {
        match tag.language.as_str() {
            "en" => Some(Self::English),
            "es" => Some(match tag.region.as_deref() {
                None | Some("es") => Self::Spanish,
                Some(_) => Self::LatinAmericanSpanish,
            }),
            "ru" => Some(Self::Russian),
            "it" => Some(Self::Italian),
            "de" => Some(Self::German),
            "fr" => Some(Self::French),
            "pt" => Some(Self::BrazilianPortuguese),
            "zh" => Some(Self::SimplifiedChinese),
            _ => None,
        }
    }

    pub fn system() -> Self {
        fastframe_i18n::detect(Self::from_tag).unwrap_or_default()
    }

    pub fn resolve(setting: UiLanguage, system: Self) -> Self {
        match setting {
            UiLanguage::System => system,
            UiLanguage::English => Self::English,
            UiLanguage::Spanish => Self::Spanish,
            UiLanguage::LatinAmericanSpanish => Self::LatinAmericanSpanish,
            UiLanguage::Russian => Self::Russian,
            UiLanguage::Italian => Self::Italian,
            UiLanguage::German => Self::German,
            UiLanguage::French => Self::French,
            UiLanguage::BrazilianPortuguese => Self::BrazilianPortuguese,
            UiLanguage::SimplifiedChinese => Self::SimplifiedChinese,
        }
    }

    pub(crate) fn endonym(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Spanish => "Español de España",
            Self::LatinAmericanSpanish => "Español de Latinoamérica",
            Self::Russian => "Русский",
            Self::Italian => "Italiano",
            Self::German => "Deutsch",
            Self::French => "Français",
            Self::BrazilianPortuguese => "Português do Brasil",
            Self::SimplifiedChinese => "简体中文",
        }
    }

    #[cfg(test)]
    pub(crate) fn source(self) -> &'static str {
        match self {
            Self::English => include_str!("../assets/i18n/cineo.pot"),
            Self::Spanish => include_str!("../assets/i18n/es.po"),
            Self::LatinAmericanSpanish => include_str!("../assets/i18n/es-419.po"),
            Self::Russian => include_str!("../assets/i18n/ru.po"),
            Self::Italian => include_str!("../assets/i18n/it.po"),
            Self::German => include_str!("../assets/i18n/de.po"),
            Self::French => include_str!("../assets/i18n/fr.po"),
            Self::BrazilianPortuguese => include_str!("../assets/i18n/pt-BR.po"),
            Self::SimplifiedChinese => include_str!("../assets/i18n/zh-CN.po"),
        }
    }
}

pub(crate) type Text = std::borrow::Cow<'static, str>;

thread_local! {
    static CURRENT: Cell<Locale> = const { Cell::new(Locale::English) };
}

pub fn set(locale: Locale) {
    CURRENT.set(locale);
}

pub(crate) fn current() -> Locale {
    CURRENT.get()
}

pub(crate) fn fill(text: &str, arguments: &[(&str, &dyn Display)]) -> Text {
    let mut filled = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(open) = rest.find('{') {
        filled.push_str(&rest[..open]);
        let after = &rest[open + 1..];
        let value = after.find('}').and_then(|close| {
            let name = &after[..close];
            arguments
                .iter()
                .find(|(n, _)| *n == name)
                .map(|(_, value)| (close, value))
        });
        match value {
            Some((close, value)) => {
                filled.push_str(&value.to_string());
                rest = &after[close + 1..];
            }
            None => {
                filled.push('{');
                rest = after;
            }
        }
    }
    filled.push_str(rest);
    filled.into()
}

macro_rules! t {
    ($source:literal $(,)?) => {
        fastframe_i18n::gettext($crate::i18n::current(), $source)
    };
    ($source:literal, $($name:ident = $value:expr),+ $(,)?) => {
        $crate::i18n::fill(
            &fastframe_i18n::gettext($crate::i18n::current(), $source),
            &[$((stringify!($name), &$value as &dyn std::fmt::Display)),+],
        )
    };
}
pub(crate) use t;

macro_rules! pt {
    ($context:literal, $source:literal $(,)?) => {
        fastframe_i18n::pgettext($crate::i18n::current(), $context, $source)
    };
    ($context:literal, $source:literal, $($name:ident = $value:expr),+ $(,)?) => {
        $crate::i18n::fill(
            &fastframe_i18n::pgettext($crate::i18n::current(), $context, $source),
            &[$((stringify!($name), &$value as &dyn std::fmt::Display)),+],
        )
    };
}
pub(crate) use pt;

