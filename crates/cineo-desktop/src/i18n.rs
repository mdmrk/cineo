#[cfg(test)]
mod tests {
    use std::collections::{BTreeMap, BTreeSet};

    use cineo_core::app::Language;

    use super::*;

    #[derive(Debug, Default)]
    struct Entry {
        context: Option<String>,
        id: String,
        text: String,
        fuzzy: bool,
    }

    fn unquote(line: &str) -> &str {
        line.trim()
            .strip_prefix('"')
            .and_then(|l| l.strip_suffix('"'))
            .unwrap_or_else(|| panic!("not a quoted string: {line:?}"))
    }

    fn entries(source: &str) -> Vec<Entry> {
        let mut entries = Vec::new();
        let mut entry = Entry::default();
        let mut field: Option<&str> = None;
        for line in source.lines().chain([""]) {
            if line.trim().is_empty() {
                if !entry.id.is_empty() {
                    entries.push(std::mem::take(&mut entry));
                }
                entry = Entry::default();
                field = None;
            } else if line.starts_with("#,") {
                entry.fuzzy |= line.contains("fuzzy");
            } else if line.starts_with('#') {
            } else if line.starts_with('"') {
                let value = unquote(line);
                match field {
                    Some("msgctxt") => entry.context.get_or_insert_default().push_str(value),
                    Some("msgid") => entry.id.push_str(value),
                    Some("msgstr") => entry.text.push_str(value),
                    _ => panic!("continuation without a field: {line:?}"),
                }
            } else {
                let (name, value) = line.split_once(' ').unwrap_or_else(|| panic!("{line:?}"));
                let value = unquote(value);
                match name {
                    "msgctxt" => entry.context = Some(value.to_owned()),
                    "msgid" => entry.id = value.to_owned(),
                    "msgstr" => entry.text = value.to_owned(),
                    _ => panic!("unexpected field {name:?}"),
                }
                field = Some(match name {
                    "msgctxt" => "msgctxt",
                    "msgid" => "msgid",
                    _ => "msgstr",
                });
            }
        }
        entries
    }

    fn arguments(text: &str) -> BTreeSet<&str> {
        text.match_indices('{')
            .filter_map(|(i, _)| text[i + 1..].split_once('}').map(|(name, _)| name))
            .filter(|name| name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'))
            .collect()
    }

    fn literal(code: &str) -> Option<(&str, &str)> {
        let code = code.trim_start().strip_prefix('"')?;
        let mut escaped = false;
        for (i, c) in code.char_indices() {
            match c {
                '\\' if !escaped => escaped = true,
                '"' if !escaped => return Some((&code[..i], &code[i + 1..])),
                _ => escaped = false,
            }
        }
        None
    }

    fn requested() -> BTreeSet<(Option<String>, String)> {
        let mut dirs = vec![std::path::PathBuf::from(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/src"
        ))];
        let mut messages = BTreeSet::new();
        while let Some(dir) = dirs.pop() {
            for entry in std::fs::read_dir(dir).unwrap() {
                let path = entry.unwrap().path();
                if path.is_dir() {
                    dirs.push(path);
                    continue;
                }
                let code = std::fs::read_to_string(&path).unwrap();
                for (i, call) in code.match_indices("t!(") {
                    let before = &code[..i];
                    let contextual = before.ends_with('p');
                    let start = if contextual { &before[..i - 1] } else { before };
                    if start.ends_with(|c: char| c.is_alphanumeric() || c == '_' || c == '"') {
                        continue;
                    }
                    let rest = &code[i + call.len()..];
                    let Some((first, rest)) = literal(rest) else {
                        continue;
                    };
                    if contextual {
                        let rest = rest.trim_start().strip_prefix(',').unwrap_or(rest);
                        let (source, _) = literal(rest).unwrap();
                        messages.insert((Some(first.to_owned()), source.to_owned()));
                    } else {
                        messages.insert((None, first.to_owned()));
                    }
                }
            }
        }
        messages
    }

    #[test]
    fn every_catalog_translates_exactly_the_messages_the_code_asks_for() {
        let requested = requested();
        assert!(requested.len() > 250, "found only {}", requested.len());
        for locale in Locale::ALL {
            let catalog: BTreeMap<_, _> = entries(locale.source())
                .into_iter()
                .filter(|e| !e.id.is_empty())
                .map(|e| ((e.context.clone(), e.id.clone()), e))
                .collect();
            let ids: BTreeSet<_> = catalog.keys().cloned().collect();
            assert_eq!(ids, requested, "{locale:?}");
            if locale == Locale::English {
                continue;
            }
            for entry in catalog.values() {
                assert!(
                    !entry.fuzzy && !entry.text.is_empty(),
                    "{locale:?}: {entry:?}"
                );
                assert_eq!(
                    arguments(&entry.text),
                    arguments(&entry.id),
                    "{locale:?}: {entry:?}"
                );
            }
        }
    }

    #[test]
    fn every_audio_and_subtitle_language_has_a_name() {
        for language in Language::all() {
            assert_ne!(
                language_name(language.code()),
                language.code(),
                "{language:?}"
            );
        }
    }

    #[test]
    fn arguments_fill_their_placeholders_once() {
        let filled = fill(
            "{name} has {count} {unknown} {",
            &[("name", &"{count}"), ("count", &2.5)],
        );
        assert_eq!(filled, "{count} has 2.5 {unknown} {");
    }

    #[test]
    fn messages_follow_the_locale_and_fall_back_to_english() {
        set(Locale::Spanish);
        assert_eq!(t!("Library"), "Biblioteca");
        assert_eq!(t!("Titles: {count}", count = 3), "Títulos: 3");
        const MISSING: &str = "No such message";
        assert_eq!(fastframe_i18n::gettext(current(), MISSING), MISSING);
        set(Locale::LatinAmericanSpanish);
        assert_eq!(t!("Settings"), "Configuración");
        set(Locale::Spanish);
        assert_eq!(t!("Settings"), "Ajustes");
        set(Locale::Russian);
        assert_eq!(t!("Titles: {count}", count = 21), "Названий: 21");
        assert_eq!(language_name("ara"), "Арабский");
        set(Locale::Italian);
        assert_eq!(t!("{percent} % played", percent = 40), "40 % riprodotto");
        set(Locale::German);
        assert_eq!(t!("Season {number}", number = 2), "Staffel 2");
        set(Locale::French);
        assert_eq!(t!("Streams: {count}", count = 4), "Flux : 4");
        set(Locale::BrazilianPortuguese);
        assert_eq!(t!("Settings"), "Configurações");
        set(Locale::SimplifiedChinese);
        assert_eq!(t!("Settings"), "设置");
        assert_eq!(t!("Streams: {count}", count = 4), "片源：4");
        set(Locale::English);
        assert_eq!(
            t!("Installed {name}", name = "Torrentio"),
            "Installed Torrentio"
        );
        assert_eq!(t!("{count} s", count = 2.5), "2.5 s");
    }

    fn tag(tag: &str) -> Option<Locale> {
        LanguageTag::parse(tag).and_then(|tag| Locale::from_tag(&tag))
    }

    #[test]
    fn the_system_tag_picks_a_locale() {
        assert_eq!(tag("es-MX"), Some(Locale::LatinAmericanSpanish));
        assert_eq!(tag("es_AR.UTF-8"), Some(Locale::LatinAmericanSpanish));
        assert_eq!(tag("es-419"), Some(Locale::LatinAmericanSpanish));
        assert_eq!(tag("es-Latn-CO"), Some(Locale::LatinAmericanSpanish));
        assert_eq!(tag("es_ES.UTF-8"), Some(Locale::Spanish));
        assert_eq!(tag("es-ES"), Some(Locale::Spanish));
        assert_eq!(tag("es"), Some(Locale::Spanish));
        assert_eq!(tag("es.UTF-8"), Some(Locale::Spanish));
        assert_eq!(tag("ru_RU.UTF-8"), Some(Locale::Russian));
        assert_eq!(tag("it-IT"), Some(Locale::Italian));
        assert_eq!(tag("de_AT.UTF-8"), Some(Locale::German));
        assert_eq!(tag("fr-CA"), Some(Locale::French));
        assert_eq!(tag("pt-BR"), Some(Locale::BrazilianPortuguese));
        assert_eq!(tag("pt_PT.UTF-8"), Some(Locale::BrazilianPortuguese));
        assert_eq!(tag("zh-CN"), Some(Locale::SimplifiedChinese));
        assert_eq!(tag("zh_TW.UTF-8"), Some(Locale::SimplifiedChinese));
        assert_eq!(tag("zh-Hant-HK"), Some(Locale::SimplifiedChinese));
        assert_eq!(tag("en-US"), Some(Locale::English));
        assert_eq!(tag("nl-NL"), None);
        assert_eq!(tag("C"), None);
        assert_eq!(
            fastframe_i18n::first_supported(["nl-NL", "de-DE", "en-US"], Locale::from_tag),
            Some(Locale::German)
        );
        assert_eq!(
            Locale::resolve(UiLanguage::System, Locale::Spanish),
            Locale::Spanish
        );
        assert_eq!(
            Locale::resolve(UiLanguage::English, Locale::Spanish),
            Locale::English
        );
    }
}
